import { mkdir, readdir, rm } from "node:fs/promises"
import { isBuiltin } from "node:module"
import path from "node:path"

const args = process.argv.slice(2)
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  throw new Error("Usage: bun scripts/build-tools.ts [--check]")
}
if (Bun.version !== "1.3.14") throw new Error("Build the prepared tools with Bun 1.3.14 (the pinned CI version)")

const root = path.resolve(import.meta.dir, "..")
const source = path.join(root, "opencode_nvim/plugins/opencode-nvim")
const destination = path.join(root, "opencode_nvim/dist/opencode-nvim")
const pkg = await Bun.file(path.join(source, "package.json")).json()
for (const name of ["zod", "@opencode/schema"]) {
  const installed = await Bun.file(path.join(source, "node_modules", name, "package.json")).json()
  if (installed.version !== pkg.dependencies[name]) throw new Error(`Install the pinned ${name} before building`)
}

const built = await Bun.build({
  entrypoints: [path.join(source, "index.ts")],
  root: source,
  target: "bun",
  format: "esm",
  minify: true,
  // OpenCode must supply its own Effect instance for cancellation, fibers, and schemas.
  external: ["effect", "effect/*", "@opencode/plugin", "@opencode/plugin/*"],
  banner: "// Generated by scripts/build-tools.ts; licenses in THIRD_PARTY_NOTICES.txt.",
})
if (!built.success) throw new AggregateError(built.logs, "Server plugin build failed")
if (built.outputs.length !== 1) throw new Error("Expected one server plugin bundle")
const bundle = await built.outputs[0].text()
for (const { path: specifier } of new Bun.Transpiler({ loader: "js", target: "bun" }).scan(bundle).imports) {
  if (!isBuiltin(specifier) && specifier !== "effect" && !specifier.startsWith("effect/")
    && specifier !== "@opencode/plugin" && !specifier.startsWith("@opencode/plugin/")) {
    throw new Error(`Unexpected runtime dependency in prepared tools: ${specifier}`)
  }
}

const files = new Map<string, string>([
  ["index.js", bundle],
  ["package.json", JSON.stringify({
    name: pkg.name, version: pkg.version, private: true, type: "module", exports: "./index.js",
  }, null, 2) + "\n"],
  ["neovim_edit.txt", await Bun.file(path.join(source, "tools/neovim_edit.txt")).text()],
  ["neovim_patch.txt", await Bun.file(path.join(source, "tools/neovim_patch.txt")).text()],
  ["THIRD_PARTY_NOTICES.txt", await Bun.file(path.join(source, "THIRD_PARTY_NOTICES.txt")).text()],
])

if (args[0] === "--check") {
  const actual = await readdir(destination).catch(() => [])
  const stale = actual.sort().join("\n") !== [...files.keys()].sort().join("\n")
  const changed = []
  for (const [name, content] of files) {
    if (await Bun.file(path.join(destination, name)).text().catch(() => undefined) !== content) changed.push(name)
  }
  if (stale || changed.length) throw new Error(`Prepared tools are stale; run bun scripts/build-tools.ts${changed.length ? ` (${changed.join(", ")})` : ""}`)
  console.log("Prepared server tools match their source")
} else {
  await rm(destination, { recursive: true, force: true })
  await mkdir(destination, { recursive: true })
  for (const [name, content] of files) await Bun.write(path.join(destination, name), content)
  console.log("Prepared server tools: opencode_nvim/dist/opencode-nvim")
}
