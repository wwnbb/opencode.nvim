describe("native session catalog operations", function()
	local state = require("opencode.state")
	local pending = require("opencode.session.pending")
	local actions = require("opencode.actions")
	local client = require("opencode.client")
	local lifecycle = require("opencode.lifecycle")
	local sessions = require("opencode.session")
	local stubs, requests, opened, scheduled, callback_result
	local function info(id, directory, title)
		return { id = id, title = title or id, directory = directory, location = { directory = directory } }
	end
	local function reply(kind, err, value)
		for _, request in ipairs(requests) do
			if request.kind == kind and not request.replied then request.replied = true; request.callback(err, value); return end
		end
		error("Missing " .. kind .. " request")
	end
	local function result(err, value) callback_result = { err = err, value = value } end
	before_each(function()
		state.reset(); pending.clear_all()
		package.loaded["opencode.session.catalog"] = nil
		stubs, requests, opened, callback_result = {}, {}, {}, nil
		local stub = require("luassert.stub")
		stubs[#stubs + 1] = stub(vim, "schedule", function(fn) fn() end)
		stubs[#stubs + 1] = stub(lifecycle, "ensure_connected", function(fn) fn() end)
		for _, method in ipairs({ "get_session", "get_location", "update_session", "move_session" }) do
			stubs[#stubs + 1] = stub(client, method, function(id, title_or_callback, callback)
				requests[#requests + 1] = { kind = method, id = id, title = callback and title_or_callback,
					callback = callback or title_or_callback }
			end)
		end
		stubs[#stubs + 1] = stub(sessions, "switch_to", function(value)
			opened[#opened + 1] = value
			state.set_session(value.id, value.title)
		end)
		state.set_session("source", "Source")
	end)
	after_each(function()
		for index = #stubs, 1, -1 do stubs[index]:revert() end
		state.reset(); pending.clear_all()
		package.loaded["opencode.session.catalog"] = nil
	end)
	it("opens by ID only after resolving the native remote location without changing cwd", function()
		local cwd = vim.fn.getcwd()
		actions.open_session("remote", {}, result)
		reply("get_session", nil, info("remote", "/remote/project"))
		assert.equals(0, #opened)
		assert.equals("/remote/project", requests[2].id)
		reply("get_location", nil, { directory = "/remote/project" })
		assert.equals("remote", opened[1].id)
		assert.is_nil(callback_result.err)
		assert.equals(cwd, vim.fn.getcwd())
	end)
	it("keeps an unknown ID and an unavailable server location from changing the session", function()
		actions.open_session("missing", {}, result)
		reply("get_session", { status = 404, message = "Unknown session ID" })
		assert.equals("Unknown session ID", callback_result.err.message)
		actions.open_session("remote", {}, result)
		reply("get_session", nil, info("remote", "/remote/project"))
		reply("get_location", { status = 404, message = "No such location" })
		assert.equals("location_unavailable", callback_result.err.code)
		assert.equals("source", state.get_session().id)
		assert.equals(0, #opened)
	end)
	it("rejects relative locations, mismatched IDs and mismatched resolved locations", function()
		for _, invalid in ipairs({ info("remote", "relative"), info("wrong", "/remote") }) do
			actions.open_session("remote", {}, result)
			reply("get_session", nil, invalid)
			assert.is_not_nil(callback_result.err)
		end
		actions.open_session("remote", {}, result)
		reply("get_session", nil, info("remote", "/remote"))
		reply("get_location", nil, { directory = "/another" })
		assert.equals("location_mismatch", callback_result.err.code)
		assert.equals(0, #opened)
	end)
	for _, phase in ipairs({ "get_session", "get_location" }) do
		it("ignores old endpoint responses during " .. phase, function()
			actions.open_session("remote", {}, result)
			if phase == "get_location" then reply("get_session", nil, info("remote", "/remote")) end
			pending.invalidate()
			reply(phase, nil, phase == "get_session" and info("remote", "/remote") or { directory = "/remote" })
			assert.equals(0, #opened)
			assert.is_nil(callback_result)
		end)
	end
	it("rejects an old open after source selection changes away and back", function()
		actions.open_session("remote", {}, result)
		state.set_session("other", "Other"); state.set_session("source", "Source")
		reply("get_session", nil, info("remote", "/remote"))
		assert.equals(1, #requests)
		assert.equals(0, #opened)
	end)
	it("opens only the latest request when responses arrive out of order", function()
		actions.open_session("first", {}, result)
		actions.open_session("second", {}, result)
		reply("get_session", nil, info("first", "/first"))
		reply("get_session", nil, info("second", "/second"))
		reply("get_location", nil, { directory = "/second" })
		assert.equals(1, #opened)
		assert.equals("second", opened[1].id)
	end)
	it("keeps an open request current when another session is renamed", function()
		actions.open_session("remote", {}, result)
		actions.rename_session("other", "Renamed")
		reply("get_session", nil, info("remote", "/remote"))
		reply("get_location", nil, { directory = "/remote" })
		assert.equals(1, #opened)
		assert.equals("remote", opened[1].id)
		assert.is_nil(callback_result.err)
		reply("update_session", nil, true)
		reply("get_session", nil, info("other", "/other", "Renamed"))
		assert.equals("Renamed", state.get_session_record("other").title)
		assert.equals("remote", state.get_session().id)
	end)
	it("does not open a different session after waiting for a connection", function()
		local connected
		lifecycle.ensure_connected = function(fn) connected = fn end
		actions.open_session("remote", {}, result)
		state.set_session("other", "Other")
		connected()
		assert.equals(0, #requests)
	end)
	it("renames an inactive session through PATCH and confirms the native title", function()
		state.upsert_session(info("remote", "/remote", "Old"), { touch = false })
		actions.rename_session("remote", " New title ", result)
		assert.equals("remote", requests[1].id)
		assert.equals("New title", requests[1].title)
		state.set_session("other", "Other")
		reply("update_session", nil, true)
		assert.equals("Old", state.get_session_record("remote").title)
		reply("get_session", nil, info("remote", "/remote", "New title"))
		assert.equals("New title", state.get_session_record("remote").title)
		assert.equals("other", state.get_session().id)
	end)
	it("regenerates a title with the native empty title and updates the current session", function()
		actions.rename_session("source", "", result)
		assert.equals("", requests[1].title)
		reply("update_session", nil, true)
		reply("get_session", nil, info("source", "/source", "Generated title"))
		assert.equals("Generated title", state.get_session().name)
	end)
	it("preserves newer SSE metadata over a late confirmation read", function()
		state.upsert_session(info("remote", "/remote", "Old"), { touch = false })
		actions.rename_session("remote", "New", result)
		reply("update_session", nil, true)
		state.upsert_session(info("remote", "/remote", "Newest event title"), { touch = false })
		reply("get_session", nil, info("remote", "/remote", "New"))
		assert.equals("Newest event title", callback_result.value.title)
		assert.equals("Newest event title", state.get_session_record("remote").title)
	end)
	it("keeps failed and superseded rename operations from mutating the local session", function()
		actions.rename_session("source", "Failed", result)
		reply("update_session", { status = 404, message = "Session unavailable" })
		assert.equals("Session unavailable", callback_result.err.message)
		assert.equals("Source", state.get_session().name)
		actions.rename_session("source", "First", result)
		actions.rename_session("source", "Second", result)
		reply("update_session", nil, true)
		reply("update_session", nil, true)
		assert.equals(4, #requests)
		reply("get_session", nil, info("source", "/source", "Second"))
		assert.equals("Second", state.get_session().name)
	end)
	it("drops a queued confirmation after connection invalidation", function()
		actions.rename_session("source", "New", result)
		reply("update_session", nil, true)
		scheduled = {}
		vim.schedule = function(fn) scheduled[#scheduled + 1] = fn end
		reply("get_session", nil, info("source", "/source", "New"))
		pending.invalidate()
		for _, fn in ipairs(scheduled) do fn() end
		assert.equals("Source", state.get_session().name)
		assert.is_nil(callback_result)
	end)
	it("sends a targeted native move and keeps local context unchanged until server events", function()
		state.upsert_session(info("source", "/remote/source"), { touch = false })
		actions.move_session("source", " ../destination ", result)
		assert.equals("source", requests[1].id)
		assert.equals("../destination", requests[1].title)
		assert.equals("/remote/source", state.get_session_directory("source"))
		state.set_session("other", "Other")
		reply("move_session", nil, true)
		assert.is_nil(callback_result.err)
		assert.equals("/remote/source", state.get_session_directory("source"))
		assert.equals("other", state.get_session().id)
	end)
	it("keeps failed and stale moves from changing the server location projection", function()
		state.upsert_session(info("source", "/remote/source"), { touch = false })
		actions.move_session("source", "/remote/new", result)
		reply("move_session", { status = 400, message = "Destination unavailable" })
		assert.equals("Destination unavailable", callback_result.err.message)
		assert.equals("/remote/source", state.get_session_directory("source"))
		callback_result = nil
		actions.move_session("source", "/remote/new", result)
		pending.invalidate(); reply("move_session", nil, true)
		assert.is_nil(callback_result)
	end)
end)
