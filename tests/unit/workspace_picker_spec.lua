describe("native project and worktree UI workflows", function()
	local actions = require("opencode.actions")
	local state = require("opencode.state")
	local pending = require("opencode.session.pending")
	local workspace = require("opencode.ui.palette.workspaces")
	local menus, inputs, calls, stubs, notices
	local project = { id = "p", name = "Remote project", canonical = "/remote/project" }
	local tree = { directory = "/remote/feature", strategy = "git_worktree" }
	local function key(opts, name, item)
		for _, mapping in ipairs(opts.keys) do
			if mapping.key == name then mapping.handler({ close = function() end }, item or opts.items[1]); return end
		end
		error("Missing menu key " .. name)
	end
	before_each(function()
		state.reset(); pending.clear_all()
		state.upsert_session({ id = "source", title = "Source", directory = "/remote/project" })
		state.set_session("source", "Source")
		menus, inputs, calls, stubs, notices = {}, {}, {}, {}, {}
		local stub = require("luassert.stub")
		stubs[#stubs + 1] = stub(require("opencode.ui.menu"), "open", function(opts) menus[#menus + 1] = opts end)
		stubs[#stubs + 1] = stub(require("opencode.ui.float"), "create_input_popup", function(opts) inputs[#inputs + 1] = opts end)
		stubs[#stubs + 1] = stub(vim, "notify", function(message) notices[#notices + 1] = message end)
		stubs[#stubs + 1] = stub(actions, "list_projects", function(cb) cb(nil, { project }) end)
		stubs[#stubs + 1] = stub(actions, "list_worktrees", function(id, cb) assert.equals("p", id); cb(nil, { { directory = project.canonical }, tree }) end)
		stubs[#stubs + 1] = stub(actions, "get_location", function(directory, cb)
			calls[#calls + 1] = { method = "location", directory = directory }
			cb(nil, { directory = directory or "/remote/default" })
		end)
		stubs[#stubs + 1] = stub(actions, "new_session", function(opts) calls[#calls + 1] = { method = "new", opts = opts } end)
		stubs[#stubs + 1] = stub(actions, "move_session", function(id, directory, cb)
			calls[#calls + 1] = { method = "move", id = id, directory = directory }; cb(nil)
		end)
		stubs[#stubs + 1] = stub(actions, "create_worktree", function(id, opts, cb)
			calls[#calls + 1] = { method = "create", id = id, opts = opts }; cb(nil, tree)
		end)
		stubs[#stubs + 1] = stub(actions, "remove_worktree", function(id, directory, force, cb)
			calls[#calls + 1] = { method = "remove", id = id, directory = directory, force = force }; cb(nil)
		end)
		stubs[#stubs + 1] = stub(actions, "refresh_worktrees", function(id, cb) calls[#calls + 1] = { method = "refresh", id = id }; cb(nil) end)
	end)
	after_each(function()
		for index = #stubs, 1, -1 do stubs[index]:revert() end
		state.reset(); pending.clear_all()
	end)
	it("creates a session in a selected remote worktree after native location resolution", function()
		workspace.new()
		menus[1].on_select(menus[1].items[3])
		menus[2].on_select(menus[2].items[1])
		menus[3].on_select(menus[3].items[2])
		assert.same({ method = "location", directory = tree.directory }, calls[1])
		assert.same({ method = "new", opts = { location = { directory = tree.directory } } }, calls[2])
		assert.equals("/remote/project", state.get_session_directory("source"))
	end)
	it("uses the server default and refuses a late resolution after another selection", function()
		workspace.new(); menus[1].on_select(menus[1].items[2])
		assert.equals("/remote/default", calls[2].opts.location.directory)
		local reply
		actions.get_location = function(_, cb) reply = cb end
		workspace.new("/remote/another")
		state.set_session("other", "Other")
		reply(nil, { directory = "/remote/another" })
		assert.equals(2, #calls)
	end)
	it("does not create a session when location support is unavailable", function()
		actions.get_location = function(_, cb) cb({ status = 404, message = "Location API unavailable" }) end
		workspace.new("/remote/another")
		assert.equals(0, #calls)
		assert.truthy(notices[1]:find("unavailable", 1, true))
	end)
	it("sends /cd arguments to the captured session and exposes a picker without arguments", function()
		local commands = {}
		workspace.register({ register = function(command) commands[command.slash.name] = command end })
		commands.cd.run({ args = "../new" })
		assert.same({ method = "move", id = "source", directory = "../new" }, calls[1])
		commands.cd.run({})
		assert.equals(" Session Location ", menus[1].title)
	end)
	it("lists projects and worktrees and makes create, open and refresh reachable", function()
		workspace.worktrees()
		menus[1].on_select(menus[1].items[1])
		assert.equals(2, #menus[2].items)
		key(menus[2], "n"); inputs[1].on_submit("feature name")
		assert.same({ method = "create", id = "p", opts = { name = "feature name" } }, calls[1])
		assert.equals(tree.directory, menus[3].message)
		menus[3].on_select("New session here")
		assert.equals(tree.directory, calls[3].opts.location.directory)
		key(menus[2], "r")
		assert.equals("refresh", calls[4].method)
		assert.equals(" Worktrees ", menus[4].title)
	end)
	it("protects project roots and requires a separate choice after a dirty-worktree refusal", function()
		workspace.worktrees(project)
		key(menus[1], "d", menus[1].items[1])
		assert.equals(1, #menus)
		assert.equals(0, #calls)
		actions.remove_worktree = function(id, directory, force, cb)
			calls[#calls + 1] = { method = "remove", id = id, directory = directory, force = force }
			if force then cb(nil) else cb({ code = "WorktreeError", message = "Dirty worktree", force_required = true }) end
		end
		key(menus[1], "d", menus[1].items[2])
		menus[2].on_select("Delete")
		assert.is_false(calls[1].force)
		assert.same({ "Delete anyway", "Cancel" }, menus[3].items)
		menus[3].on_select("Cancel")
		assert.equals(1, #calls)
		menus[3].on_select("Delete anyway")
		assert.is_true(calls[2].force)
		assert.equals(tree.directory, calls[2].directory)
	end)
	it("does not force-delete a worktree after the connection changes", function()
		actions.remove_worktree = function(_, _, _, cb) calls[#calls + 1] = {}; cb({ message = "Dirty", force_required = true }) end
		workspace.worktrees(project); key(menus[1], "d", menus[1].items[2]); menus[2].on_select("Delete")
		pending.invalidate(); menus[3].on_select("Delete anyway")
		assert.equals(1, #calls)
	end)
end)
