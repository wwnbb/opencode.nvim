describe("native session tabs", function()
	local state = require("opencode.state")
	local bus = require("opencode.events.bus")
	local client = require("opencode.client")
	local tabs = require("opencode.session.tabs")
	local pending = require("opencode.session.pending")
	local session = require("opencode.session")
	local saved_view, saved_get, saved_messages, saved_defer, requests, timers, directory
	local function unread(id) return require("opencode.selectors").get_session_view(id):is_unread() end
	local function seed(id, idle, viewed)
		state.upsert_session({ id = id, title = id, directory = "/project", time = { created = 1, idle = idle, viewed = viewed } })
	end
	before_each(function()
		tabs.teardown(); state.reset(); pending.clear_all(); bus.clear()
		directory = vim.fn.tempname(); vim.fn.mkdir(directory, "p")
		state.set_config({ server = { host = "localhost", port = 4096 }, chat = { session_tabs = { persist = false } } })
		saved_view, saved_get, saved_messages, saved_defer = client.view_session, client.get_session, client.get_messages, vim.defer_fn
		requests, timers = {}, {}
		client.view_session = function(id, idle, callback) requests[#requests + 1] = { id = id, idle = idle, callback = callback } end
		client.get_messages = function() end
		vim.defer_fn = function(callback, delay)
			local timer = { callback = callback, delay = delay, cancelled = false }
			function timer:stop() self.cancelled = true end
			function timer:close() self.cancelled = true end
			timers[#timers + 1] = timer
			return timer
		end
		tabs.setup(bus)
		state.set_connection("connected")
	end)
	after_each(function()
		tabs.teardown(); bus.clear(); state.reset(); pending.clear_all()
		client.view_session, client.get_session, client.get_messages, vim.defer_fn = saved_view, saved_get, saved_messages, saved_defer
		vim.fn.delete(directory, "rf")
	end)

	it("preserves time metadata through partial updates and stale viewed events", function()
		seed("s", 30, 10)
		state.upsert_session({ id = "s", time = { updated = 40 } }, { touch = false })
		assert.same({ created = 1, updated = 40, idle = 30, viewed = 10 }, state.get_session_record("s").time)
		state.upsert_session({ id = "s", time = { idle = 20, viewed = 5 } }, { touch = false })
		assert.is_true(unread("s"))
		assert.equals(30, state.get_session_record("s").time.idle)
		assert.equals(10, state.get_session_record("s").time.viewed)
		local handler = require("opencode.events.handlers.server")
		handler.setup(bus)
		bus.emit("server_event", { id = "evt_view", type = "session.viewed", created = 100, data = { sessionID = "s", idle = 30 } })
		assert.equals(30, state.get_session_record("s").time.viewed)
		assert.equals(40, state.get_session_record("s").time.updated)
		assert.is_false(unread("s"))
		handler.clear()
	end)

	it("acknowledges the observed completion once and keeps a newer completion unread", function()
		seed("s", 30, 10)
		tabs.observe("s", false); assert.equals(0, #requests)
		tabs.observe("s", true); tabs.observe("s", true)
		assert.equals(1, #requests); assert.equals(30, requests[1].idle)
		state.upsert_session({ id = "s", time = { idle = 40 } }, { touch = false })
		requests[1].callback(nil)
		assert.equals(30, state.get_session_record("s").time.viewed)
		assert.is_true(unread("s"))
		tabs.observe("s", true)
		assert.equals(2, #requests); assert.equals(40, requests[2].idle)
		requests[2].callback(nil); assert.is_false(unread("s"))
	end)
	it("acknowledges two visible sessions independently while one response is pending", function()
		seed("first", 30); seed("second", 40)
		tabs.observe("first", true); tabs.observe("second", true)
		assert.equals(2, #requests)
		requests[2].callback(nil); requests[1].callback(nil)
		assert.is_false(unread("first")); assert.is_false(unread("second"))
	end)

	it("only acknowledges while focused and retries temporary failures with bounded backoff", function()
		seed("s", 30)
		vim.api.nvim_exec_autocmds("FocusLost", {})
		tabs.observe("s", true); assert.equals(0, #requests)
		vim.api.nvim_exec_autocmds("FocusGained", {}); assert.equals(1, #requests)
		requests[1].callback({ retryable = true }); assert.equals(1000, timers[1].delay)
		timers[1].callback(); requests[2].callback({ retryable = true }); assert.equals(2000, timers[2].delay)
		vim.api.nvim_exec_autocmds("FocusLost", {}); timers[2].callback()
		assert.equals(2, #requests)
		vim.api.nvim_exec_autocmds("FocusGained", {}); assert.equals(3, #requests)
		requests[3].callback({ status = 401, retryable = false }); assert.equals(2, #timers)
		tabs.observe("s", true); assert.equals(3, #requests)
	end)

	it("invalidates timers and acknowledgements on disconnect", function()
		seed("s", 30)
		tabs.observe("s", true); requests[1].callback({ retryable = true })
		bus.emit("disconnected", {})
		assert.is_true(timers[1].cancelled)
		timers[1].callback(); requests[1].callback(nil)
		assert.is_true(unread("s")); assert.equals(1, #requests)
	end)

	it("retries a failed acknowledgement after hiding while preserving in-flight deduplication", function()
		seed("s", 30)
		tabs.observe("s", true)
		tabs.observe("s", false); tabs.observe("s", true)
		assert.equals(1, #requests)
		requests[1].callback({ retryable = true })
		tabs.observe("s", false)
		assert.is_true(timers[1].cancelled)
		tabs.observe("s", true)
		assert.equals(2, #requests)
		timers[1].callback(); requests[1].callback(nil)
		assert.is_true(unread("s"))
		requests[2].callback(nil)
		assert.is_false(unread("s"))
	end)

	it("ignores old callbacks after observing the same completion again", function()
		seed("s", 30)
		tabs.observe("s", true); requests[1].callback({ retryable = true })
		tabs.clear(); tabs.observe("s", true)
		assert.is_true(timers[1].cancelled)
		timers[1].callback(); requests[1].callback(nil)
		assert.is_true(unread("s")); assert.equals(2, #requests)
		requests[2].callback(nil)
		assert.is_false(unread("s"))
	end)

	it("restores tab order and closed tabs from the same server and scope", function()
		state.set_config({ server = { host = "localhost", port = 4096 }, chat = { session_tabs = { file = directory .. "/tabs.json" } } })
		tabs.setup(bus)
		seed("first"); seed("second"); seed("third")
		state.set_session("second", "Second")
		assert.is_true(tabs.reorder("third", -1))
		state.close_runtime_session("first")
		local expected = state.get_runtime_session_order()
		tabs.teardown(); state.reset(); tabs.setup(bus)
		assert.same(expected, state.get_runtime_session_order())
		assert.same({ "first" }, state.get_closed_session_order())
		assert.equals("second", state.get_session().id)
		client.get_session = function(id, callback) callback(nil, { id = id, title = "Reopened" }) end
		tabs.reopen()
		tabs.teardown(); state.reset(); tabs.setup(bus)
		assert.same({ "third", "second", "first" }, state.get_runtime_session_order())
		assert.same({}, state.get_closed_session_order())
		assert.equals("first", state.get_session().id)
		state.close_runtime_session("first"); state.set_session("second", "Second")
		client.get_session = function(_, callback) callback({ status = 404, message = "Missing session" }) end
		tabs.reopen()
		tabs.teardown(); state.reset(); tabs.setup(bus)
		assert.same(expected, state.get_runtime_session_order())
		assert.same({}, state.get_closed_session_order())
		assert.is_nil(state.get_session_record("first"))
		tabs.teardown(); state.reset()
		state.set_config({ server = { host = "other", port = 4096 }, chat = { session_tabs = { file = directory .. "/tabs.json" } } })
		tabs.setup(bus); assert.same({}, state.get_runtime_session_order())
	end)

	it("reopens a closed tab using server metadata without deleting it", function()
		seed("s"); state.set_session("s", "s"); state.close_runtime_session("s"); state.set_session(nil)
		client.get_session = function(id, callback) callback(nil, { id = id, title = "Updated", directory = "/project" }) end
		tabs.reopen()
		assert.is_true(state.is_runtime_session("s")); assert.equals("Updated", state.get_session().name)
		assert.same({}, state.get_closed_session_order())
		state.close_runtime_session("s"); state.set_session(nil)
		client.get_session = function(_, callback) requests[#requests + 1] = { callback = callback } end
		tabs.reopen(); state.set_session("other", "other")
		requests[1].callback(nil, { id = "s", title = "Late" })
		assert.equals("other", state.get_session().id)
	end)
	it("separates explicit URL origins and proxy paths without persisting credentials", function()
		local file = directory .. "/url-tabs.json"
		local function configure(url)
			state.set_config({ server = { url = url, auth = { username = "user", password = "public-test-only" } },
				chat = { session_tabs = { file = file } } })
			tabs.setup(bus)
		end
		configure("https://EXAMPLE.test/proxy-a/")
		seed("url-session"); state.set_session("url-session", "Session")
		configure("https://example.test/proxy-b")
		assert.same({}, state.get_runtime_session_order()); assert.is_nil(state.get_session().id)
		configure("http://example.test/proxy-a")
		assert.same({}, state.get_runtime_session_order())
		configure("https://other.test/proxy-a")
		assert.same({}, state.get_runtime_session_order())
		configure("https://example.test:443/proxy-a")
		assert.same({ "url-session" }, state.get_runtime_session_order())
		local encoded = table.concat(vim.fn.readfile(file), "\n")
		assert.is_nil(encoded:find("public-test-only", 1, true))
		configure("https://user:secret@example.test/proxy-a")
		assert.same({}, state.get_runtime_session_order())
		assert.equals(encoded, table.concat(vim.fn.readfile(file), "\n"))
	end)

	it("renders hidden completion as unread and stops observing a closed chat", function()
		local cs = require("opencode.ui.chat.state").state
		local previous = { visible = cs.visible, bufnr = cs.bufnr, winid = cs.winid, config = cs.config, tabpage = cs.tabpage }
		local window = vim.api.nvim_get_current_win()
		vim.cmd("vsplit")
		local win = vim.api.nvim_get_current_win()
		local buf = vim.api.nvim_create_buf(false, true)
		vim.api.nvim_win_set_buf(win, buf)
		cs.visible, cs.bufnr, cs.winid, cs.config = true, buf, win, { layout = "vertical", session_tabs = { max_tabs = 3 } }
		cs.tabpage = vim.api.nvim_win_get_tabpage(win)
		local ok, failure = pcall(function()
			seed("visible"); seed("hidden", 30)
			state.set_session("visible", "visible")
			local ui = require("opencode.ui.chat.session_tabs")
			ui.update_winbar()
			local bar = vim.api.nvim_eval_statusline(vim.wo[win].winbar, { winid = win, use_winbar = true }).str
			assert.is_truthy(bar:find("◆ hidden", 1, true))
			assert.equals(0, #requests)
			state.set_session("hidden", "hidden"); ui.update_winbar()
			assert.equals(1, #requests)
			cs.visible = false; ui.update_winbar()
			state.upsert_session({ id = "hidden", time = { idle = 40 } }, { touch = false })
			vim.api.nvim_exec_autocmds("FocusLost", {}); vim.api.nvim_exec_autocmds("FocusGained", {})
			assert.equals(1, #requests)
		end)
		cs.visible, cs.bufnr, cs.winid, cs.config = previous.visible, previous.bufnr, previous.winid, previous.config
		cs.tabpage = previous.tabpage
		vim.api.nvim_win_close(win, true); vim.api.nvim_buf_delete(buf, { force = true }); vim.api.nvim_set_current_win(window)
		assert.is_true(ok, failure)
	end)
end)
