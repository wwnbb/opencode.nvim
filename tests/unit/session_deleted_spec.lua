describe("opencode session deleted handling", function()
	local state, sync = require("opencode.state"), require("opencode.sync")
	local sessions = require("opencode.session")
	after_each(function() state.reset(); sync.clear_all() end)

	it("prunes deleted runtime tabs and switches the active view", function()
		state.reset(); sync.clear_all()
		local events = require("opencode.events")
		events.setup()
		sessions.set_active("del-root-a", "Root A")
		sessions.set_active("del-root-b", "Root B")
		sync.handle_message_updated({ id = "del-root-b-msg", sessionID = "del-root-b", role = "user", time = { created = 1 } })

		events.emit("server_event", { id = "evt-delete-b", type = "session.deleted",
			data = { sessionID = "del-root-b" }, created = 1 })
		assert.is_true(vim.wait(500, function() return state.get_session().id == "del-root-a" end, 10))
		assert.is_false(state.is_runtime_session("del-root-b"))
		assert.equals(0, #sync.get_messages("del-root-b"))
		for _, session in ipairs(state.get_active_sessions()) do assert.is_not.equals("del-root-b", session.id) end

		require("tests.helpers.schedule").with(function(flush)
			events.emit("server_event", { id = "evt-delete-foreign", type = "session.deleted",
				data = { sessionID = "del-foreign" }, created = 2 })
			flush()
			assert.equals("del-root-a", state.get_session().id)
		end)

		assert.is_true(sessions.handle_deleted("del-root-a"))
		assert.is_nil(state.get_session().id)
		assert.is_false(sessions.handle_deleted("del-unknown"))
		assert.is_false(sessions.handle_deleted(""))
	end)

	it("leaves the child view when its root tab is deleted", function()
		for _, with_neighbor in ipairs({ true, false }) do
			state.reset(); sync.clear_all()
			if with_neighbor then sessions.set_active("neighbor", "Neighbor") end
			sessions.set_active("parent", "Parent")
			sync.handle_message_updated({ id = "parent-msg", sessionID = "parent", role = "assistant" })
			sync.record_task_child_session("parent", "parent-msg", "task", "child")
			sessions.set_active("child", "Child", { runtime = false })
			sync.handle_message_updated({ id = "child-msg", sessionID = "child", role = "assistant" })

			assert.is_true(sessions.handle_deleted("parent"))
			assert.equals(with_neighbor and "neighbor" or nil, state.get_session().id)
			assert.is_false(state.is_runtime_session("parent"))
			assert.is_nil(state.get_session_record("parent"))
			assert.is_nil(state.get_session_record("child"))
			assert.same({}, sync.get_messages("parent"))
			assert.same({}, sync.get_messages("child"))
		end
	end)

	it("prunes a deleted child session and its local state without closing the parent tab", function()
		state.reset(); sync.clear_all()
		local locks, pending = require("opencode.session.lock"), require("opencode.session.pending")
		local permissions, forms = require("opencode.permission.state"), require("opencode.question.state")
		sessions.set_active("del-parent", "Parent")
		sync.handle_message_updated({ id = "del-parent-msg", sessionID = "del-parent", role = "assistant", time = { created = 1 } })
		sync.record_task_child_session("del-parent", "del-parent-msg", "del-parent-task", "del-child")
		sessions.remember({ id = "del-child", title = "Child" })
		sessions.set_active("del-child", "Child", { runtime = false })
		sync.handle_message_updated({ id = "del-child-msg", sessionID = "del-child", role = "assistant", time = { created = 2 } })
		locks.set("del-child", { agent = "explore" }); locks.set("del-parent", { agent = "build" })
		permissions.add_permission("child-permission", "del-child", "read", {})
		forms.add_form({ id = "child-form", sessionID = "del-child", fields = { { key = "text", type = "string" } } })
		local token = pending.token("del-child")

		assert.is_true(sessions.handle_deleted("del-child"))
		assert.is_true(state.is_runtime_session("del-parent"))
		assert.equals(1, #sync.get_messages("del-parent"))
		assert.equals(0, #sync.get_messages("del-child"))
		assert.is_nil(state.get_session_record("del-child"))
		assert.is_not.equals("del-child", state.get_session().id)
		assert.is_false(locks.is_locked("del-child"))
		assert.is_true(locks.is_locked("del-parent"))
		assert.is_nil(permissions.get_permission("child-permission"))
		assert.is_nil(forms.get_question("child-form"))
		assert.is_false(pending.is_current(token))
		locks.clear_all(); permissions.clear_all(); forms.clear_all(); pending.clear_all()
	end)
end)
