-- A session whose own turn ended keeps presenting as running while a subagent
-- below it works: tabs, the processing footer and render scope share one rule.
describe("session activity", function()
	local state = require("opencode.state")
	local sync = require("opencode.sync")
	local selectors = require("opencode.selectors")
	local tab_label = require("opencode.ui.chat.tab_label")

	local function reset()
		state.reset()
		sync.clear_all()
	end

	before_each(function()
		reset()
		state.upsert_session({ id = "root", title = "Root" }, { touch = false })
		state.upsert_session({ id = "child", parentID = "root" }, { touch = false })
		state.upsert_session({ id = "grandchild", parentID = "child" }, { touch = false })
		state.upsert_session({ id = "other", title = "Other" }, { touch = false })
		state.set_runtime_session_order({ "root", "other" })
	end)
	after_each(reset)

	it("walks a session's lineage up to its root", function()
		assert.same({ "grandchild", "child", "root" }, selectors.session_lineage("grandchild"))
		assert.same({ "root" }, selectors.session_lineage("root"))
		assert.same({}, selectors.session_lineage(nil))
	end)

	it("separates a session's own execution from the subagents still working below it", function()
		state.set_session_status("root", { type = "idle" })
		state.set_session_status("grandchild", { type = "busy" })
		local root = selectors.session_activity("root")
		assert.is_false(root.busy)
		assert.same({ "grandchild" }, root.delegated)
		assert.is_true(root.running)
		assert.same({ "grandchild" }, selectors.session_activity("child").delegated)
		assert.is_false(selectors.session_activity("other").running)
		local grandchild = selectors.session_activity("grandchild")
		assert.is_true(grandchild.busy)
		assert.same({}, grandchild.delegated)

		state.set_session_status("grandchild", { type = "idle" })
		assert.is_false(selectors.session_activity("root").running)
	end)

	it("presents a tab as Running while only its subagent works", function()
		state.set_session_status("child", { type = "retry", attempt = 1 })
		local views = selectors.get_active_session_views({ session_id = "root" })
		assert.equals(2, #views)
		local root, other = views[1], views[2]
		assert.equals("root", root.id)
		assert.is_false(root:is_busy())
		assert.equals(1, root:delegated_count())
		assert.is_true(root:is_running())
		assert.equals("Running", tab_label.status({ root }))
		assert.equals("Idle", tab_label.status({ other }))
		assert.is_true(selectors.get_session_view("root"):is_running())
	end)

	it("extends a subagent's status change to every ancestor's view", function()
		local coordinator = require("opencode.ui.chat.render_coordinator")
		local data = { session_id = "grandchild", status = { type = "idle" } }
		local scoped = coordinator.with_ancestor_scope(data)
		assert.same({ grandchild = true, child = true, root = true }, scoped._render_sessions)
		assert.is_nil(data._render_sessions)
		assert.is_true(coordinator.request_relevant(coordinator.merge_requests(nil, scoped), "root"))
		assert.is_false(coordinator.request_relevant(coordinator.merge_requests(nil, scoped), "other"))
		assert.same({ reason = "x" }, coordinator.with_ancestor_scope({ reason = "x" }))
	end)
end)
