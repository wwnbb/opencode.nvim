local sync = require("opencode.sync")
local projection = require("opencode.protocol.messages")
local metadata = require("opencode.ui.chat.history_metadata")

describe("native turn token accounting", function()
	local function put(message) sync.handle_session_messages("turns", { projection.project("turns", message) }) end
	local function assistant(id, created, finish, usage)
		return { id = id, type = "assistant", finish = finish, time = { created = created }, content = {},
			tokens = usage or { input = 10, output = 2, reasoning = 1, cache = { read = 20, write = 3 } } }
	end
	local function get(messages, boundary) return metadata.get("turns", messages or sync.get_messages("turns"), boundary, false) end
	before_each(function() sync.clear_all(); metadata.clear() end)
	after_each(function() sync.clear_all(); metadata.clear() end)
	it("keeps steers and compaction inside a modern idle-delimited turn with correct cache write accounting", function()
		put({ id = "u", type = "user", text = "Start", time = { created = 0 } })
		put(assistant("a", 1, "tool-calls"))
		put({ id = "steer", type = "user", text = "Steer", time = { created = 2 } })
		put({ id = "compact", type = "compaction", status = "completed", time = { created = 3 } })
		put(assistant("b", 4, "stop"))
		put({ id = "idle", type = "idle", time = { created = 5 } })
		local turn = assert(get().turn("b"))
		assert.same({ input = 20, output = 4, reasoning = 2, cached = 40, cache_write = 6, new = 32, total = 72, steps = 2, complete = true }, turn)
		assert.is_nil(get().turn("a"))
		turn.total = -1; assert.equals(72, get().turn("b").total)
		put({ id = "next", type = "user", text = "Next", time = { created = 6 } })
		put(assistant("c", 7, "stop"))
		assert.is_nil(get().turn("c"), "terminal steps cannot close a modern turn before idle")
		put({ id = "idle2", type = "idle", time = { created = 8 } })
		assert.equals(36, get().turn("c").total)
	end)
	it("closes legacy terminal/error turns and invalidates cached totals when a finish changes", function()
		put({ id = "u", type = "user", time = { created = 0 } })
		local step = assistant("a", 1, "tool-calls"); put(step)
		assert.is_nil(get().turn("a"))
		step.finish = "stop"; put(step); assert.equals(36, get().turn("a").total)
		put({ id = "v", type = "user", time = { created = 2 } })
		step = assistant("b", 3, "unknown"); put(step); assert.is_nil(get().turn("b"))
		step.error = { message = "failed" }; put(step); assert.equals(36, get().turn("b").total)
	end)
	it("marks missing usage/prompt as partial, applies visible revert history, and rejects overflowing totals", function()
		put(assistant("a", 0, "tool-calls"))
		put(assistant("unknown", 1, "tool-calls", {}))
		put(assistant("b", 2, "stop"))
		assert.is_false(get().turn("b").complete); assert.equals(72, get().turn("b").total)
		local visible = { sync.get_message("turns", "a") }
		assert.is_nil(get(visible, "unknown").turn("b"))
		assert.equals(72, get().turn("b").total)
		local huge = { input = 1e308, output = 0, reasoning = 0, cache = { read = 0, write = 0 } }
		put(assistant("c", 3, "tool-calls", huge)); put(assistant("d", 4, "stop", huge))
		assert.is_nil(get().turn("d"))
	end)
end)
