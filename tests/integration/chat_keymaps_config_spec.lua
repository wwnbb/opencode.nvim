local surfaces = require("tests.helpers.chat_surface")
local chat = require("opencode.ui.chat")
local state = require("opencode.ui.chat.state").state
local app = require("opencode.state")
local events = require("opencode.events")
local keys = require("opencode.util.keymap")

describe("chat keymap reconfiguration", function()
	local surface
	local function mapping(lhs)
		for _, map in ipairs(vim.api.nvim_buf_get_keymap(surface.bufnr, "n")) do
			if keys.matches(map.lhs, lhs) then return map end
		end
	end
	local function configure(close)
		app.set_config({ chat = { layout = "vertical", width = 40,
			session_tabs = { enabled = false }, keymaps = { close = close } } })
	end
	local function assert_preserved()
		assert.equals(surface.bufnr, state.bufnr)
		assert.is_truthy(table.concat(vim.api.nvim_buf_get_lines(surface.bufnr, 0, -1, false), "\n")
			:find("Preserved transcript", 1, true))
		assert.equals(1, #vim.api.nvim_get_autocmds({ group = "OpenCodeChatKeymaps_" .. surface.bufnr }))
	end
	before_each(function()
		surface = surfaces.setup()
		vim.cmd("vsplit")
		state.winid = vim.api.nvim_get_current_win()
		chat.create()
		chat.setup({ session_tabs = { enabled = false } })
		chat.add_message("system", "Preserved transcript", { render = false })
		chat.do_render()
	end)
	after_each(function()
		chat.close()
		vim.wait(30)
		surfaces.restore(surface)
	end)

	it("replaces and disables owned mappings after config events without replacing the transcript", function()
		assert.is_truthy(mapping("q"))
		configure("<F12>")
		events.emit("config_change", {})
		assert.is_true(vim.wait(500, function() return mapping("<F12>") ~= nil end, 5))
		assert.is_nil(mapping("q"))
		assert_preserved()
		local callback = mapping("<F12>").callback
		chat.setup({ auto_scroll = false })
		assert.equals(callback, mapping("<F12>").callback, "unchanged keys should not be reinstalled")
		configure(false)
		events.emit("config_change", {})
		assert.is_true(vim.wait(500, function() return mapping("<F12>") == nil end, 5))
		assert.is_nil(mapping("q"))
		assert_preserved()
	end)

	it("applies current keys on reopen and honors direct setup for the reused buffer", function()
		chat.close()
		configure("<F12>")
		chat.open()
		assert.is_nil(mapping("q"))
		assert.is_truthy(mapping("<F12>"))
		assert_preserved()
		mapping("<F12>").callback()
		assert.is_false(state.visible)
		configure(false)
		chat.open()
		assert.is_nil(mapping("<F12>"))
		assert.is_nil(mapping("q"))
		chat.setup({ keymaps = { close = { "<F10>", "<F11>" } } })
		assert.is_truthy(mapping("<F10>"))
		assert.is_truthy(mapping("<F11>"))
		chat.close()
		chat.open()
		assert.is_truthy(mapping("<F10>"))
		assert_preserved()
	end)
end)
