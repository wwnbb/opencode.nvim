describe("context placeholders in the composer", function()
	local state = require("opencode.state")
	local input = require("opencode.ui.input")
	local history = require("opencode.ui.input.history")
	local context = require("opencode.context")
	local automatic = require("opencode.editor_context")
	local source, original, submitted
	local function open(text, opts)
		vim.api.nvim_set_current_buf(source)
		input.show(vim.tbl_extend("force", {
			text = text, allow_chat_commands = true, close_on_send = false,
			on_send = function(value, parts, options)
				submitted = { text = value, options = vim.tbl_extend("force", options or {}, { parts = parts }) }
			end,
		}, opts or {}))
	end
	local function send()
		vim.fn.maparg("<C-g>", "n", false, true).callback()
		assert.is_not_nil(submitted)
		return assert(context.expand(submitted.text, submitted.options, submitted.options._context_snapshot))
	end
	before_each(function()
		state.reset(); history.clear(); context.clear(); automatic.clear(); submitted = nil
		state.set_config(vim.deepcopy(require("opencode.config").defaults))
		state.set_session("context_session", "Context")
		original = vim.api.nvim_get_current_buf()
		source = vim.api.nvim_create_buf(true, false)
		vim.api.nvim_buf_set_name(source, vim.fn.tempname() .. ".lua")
		vim.api.nvim_set_current_buf(source)
		vim.api.nvim_buf_set_lines(source, 0, -1, false, { "local before = 1", "return before" })
		vim.bo[source].filetype = "lua"
		automatic.setup()
	end)
	after_each(function()
		input.close(false)
		vim.cmd("stopinsert")
		vim.api.nvim_set_current_buf(original)
		if vim.api.nvim_buf_is_valid(source) then vim.api.nvim_buf_delete(source, { force = true }) end
		history.clear(); automatic.clear(); context.clear(); state.reset()
	end)
	it("freezes unsaved contents before mounting and keeps history as placeholders", function()
		open("Explain @buffer")
		vim.api.nvim_buf_set_lines(source, 0, -1, false, { "local after = 2" })
		local prepared = send()
		assert.is_truthy(prepared.text:find("local before = 1", 1, true))
		assert.is_nil(prepared.text:find("local after = 2", 1, true))
		assert.equals("Explain @buffer", submitted.text)
		assert.is_nil(submitted.options.context)
		assert.is_false(automatic.status("context_session") == "sent")
		local saved = vim.json.decode(table.concat(vim.fn.readfile(state.get_config().input.history_file), "\n"))
		assert.equals("Explain @buffer", saved.entries[#saved.entries].text)
		assert.is_nil(vim.inspect(saved):find("local before = 1", 1, true))
	end)
	it("retains the snapshot through focus but refreshes on a new opening", function()
		open("@buffer")
		vim.api.nvim_buf_set_lines(source, 0, -1, false, { "local newer = 3" })
		input.show({ text = "ignored" })
		assert.is_truthy(send().text:find("local before = 1", 1, true))
		input.close(false)
		open("@buffer")
		assert.is_truthy(send().text:find("local newer = 3", 1, true))
	end)
	it("can send a frozen snapshot after its original buffer is deleted", function()
		open("@this")
		vim.api.nvim_buf_delete(source, { force = true })
		assert.is_truthy(send().text:find("local before = 1", 1, true))
	end)
	it("uses a restored range instead of a supplied cursor snapshot", function()
		local snapshot = assert(context.capture())
		open("@this", { send_options = { range = { 2, 2 } }, context_snapshot = snapshot })
		vim.api.nvim_buf_set_lines(source, 1, 2, false, { "changed after opening" })
		local prepared = send()
		assert.same({ 2, 2 }, submitted.options.range)
		assert.is_truthy(prepared.text:find("return before", 1, true))
		assert.is_nil(prepared.text:find("local before = 1", 1, true))
		assert.is_nil(prepared.text:find("changed after opening", 1, true))
	end)
	it("retains an opening range error when later source changes make the range valid", function()
		open("@this", { send_options = { range = { 2, 3 } } })
		vim.api.nvim_buf_set_lines(source, 2, 2, false, { "new third line" })
		vim.fn.maparg("<C-g>", "n", false, true).callback()
		assert.equals("@this", submitted.text)
		assert.same({ 2, 3 }, submitted.options.range)
		assert.is_string(submitted.options._context_error)
		assert.is_nil(submitted.options._context_snapshot)
	end)
	it("updates context when replacing the visible draft's range", function()
		open("@this")
		input.set_pending_draft("@this", {}, { options = { range = { 2, 2 } } })
		local prepared = send()
		assert.is_truthy(prepared.text:find("return before", 1, true))
		assert.is_nil(prepared.text:find("local before = 1", 1, true))
		assert.is_nil(submitted.options._context_error)
	end)
	it("uses the next session's restored draft range", function()
		history.set_pending("@this", {}, "other_context")
		history.set_pending_options({ range = { 2, 2 } }, "other_context")
		open("@this")
		state.set_session("other_context", "Other context")
		local prepared = send()
		assert.is_truthy(prepared.text:find("return before", 1, true))
		assert.is_nil(prepared.text:find("local before = 1", 1, true))
	end)
	it("suppresses only automatic context and preserves explicit context parts", function()
		local supplied = { type = "text", text = "User supplied context" }
		local automatic_part = assert(automatic.pending("context_session"))
		open("@buffer", { send_options = { context = { automatic_part, supplied } } })
		local prepared = send()
		assert.same({ supplied }, prepared.options.context)
		assert.equals(2, #submitted.options.context)
	end)
	it("works when automatic editor context is disabled", function()
		local config = vim.deepcopy(state.get_config()); config.input.editor_context = false; state.set_config(config)
		open("@buffer")
		assert.is_nil(input.get_editor_context())
		assert.is_truthy(send().text:find("local before = 1", 1, true))
	end)
	it("does not capture prompt placeholders for shell, slash or review submissions", function()
		for _, opts in ipairs({ { mode = "shell" }, {}, { allow_chat_commands = false, persist_pending = false } }) do
			local text = next(opts) and "@buffer" or "/command @buffer"
			open(text, opts)
			vim.fn.maparg("<C-g>", "n", false, true).callback()
			assert.equals(text, submitted.text)
			assert.is_nil(submitted.options._context_snapshot)
			input.close(false)
		end
	end)
end)
