describe("automatic editor context in the composer", function()
	local state, input = require("opencode.state"), require("opencode.ui.input")
	local context = require("opencode.editor_context")
	local source, original, config, submitted
	local function send() vim.fn.maparg("<C-g>", "n", false, true).callback() end
	local function open(text, mode)
		vim.api.nvim_set_current_buf(source)
		input.show({ text = text, mode = mode, close_on_send = false,
			on_send = function(value, parts, opts) submitted = { value, parts, opts } end })
	end
	before_each(function()
		state.reset(); context.clear(); submitted = nil
		config = vim.deepcopy(require("opencode.config").defaults)
		config.settings = { file = vim.fn.tempname() }
		state.set_config(require("opencode.settings").setup(config)); state.set_session("s", "Session")
		original = vim.api.nvim_get_current_buf()
		source = vim.api.nvim_create_buf(true, false)
		vim.api.nvim_buf_set_name(source, vim.fn.tempname() .. ".lua")
		vim.api.nvim_set_current_buf(source)
		vim.api.nvim_buf_set_lines(source, 0, -1, false, { "local unsaved = 42", "print(unsaved)" })
		vim.bo[source].filetype = "lua"
		context.setup()
	end)
	after_each(function()
		input.close(false); context.clear(); require("opencode.ui.input.history").clear()
		vim.api.nvim_set_current_buf(original); vim.api.nvim_buf_delete(source, { force = true })
		pcall(vim.api.nvim_del_augroup_by_name, "OpenCodeEditorContext")
		pcall(vim.api.nvim_del_augroup_by_name, "OpenCodeSettings")
		vim.fn.delete(config.settings.file); state.reset()
	end)
	it("previews bounded unsaved text, sends once and exposes pending/sent status", function()
		open("explain")
		local part = assert(input.get_editor_context())
		assert.equals("pending", context.status("s", part))
		assert.is_truthy(part.text:find("local unsaved = 42", 1, true)); assert.is_true(#part.text <= 8192)
		send()
		assert.equals("sent", context.status("s")); assert.equals(1, #submitted[3].context)
		local payload = assert(require("opencode.protocol.requests").prompt(submitted[1], { context = submitted[3].context }, "msg_1"))
		assert.is_truthy(payload.text:find("local unsaved = 42", 1, true))
		input.close(false); open("again")
		assert.is_nil(input.get_editor_context())
	end)
	it("collects buffer context without filesystem searches or duplicate payload encoding", function()
		local root, encode = vim.fs.root, vim.json.encode
		local searches, payload_encodes = 0, 0
		vim.fs.root = function(...) searches = searches + 1; return root(...) end
		vim.json.encode = function(value, ...)
			if type(value) == "table" and value.text then payload_encodes = payload_encodes + 1 end
			return encode(value, ...)
		end
		local ok, part = pcall(context.pending, "s")
		vim.fs.root, vim.json.encode = root, encode
		assert.is_true(ok, part)
		assert.is_not_nil(part)
		assert.equals(0, searches)
		assert.equals(2, payload_encodes)
		assert.is_truthy(part.text:find("print(unsaved)", 1, true))
	end)
	it("dismisses the snapshot, refreshes it explicitly and persists an opt-out", function()
		open("draft"); input.dismiss_editor_context()
		assert.equals("dismissed", context.status("s")); assert.is_nil(input.get_editor_context())
		assert.is_not_nil(input.refresh_editor_context())
		assert.is_true(require("opencode.settings").apply("editor_context", false, "global"))
		input.close(false); open("without context")
		assert.is_nil(input.get_editor_context()); send(); assert.is_nil((submitted[3] or {}).context)
		local prefs = require("opencode.util.json_file").read(config.settings.file)
		assert.is_false(prefs.settings.global.editor_context)
	end)
	it("keeps slash and shell submissions free of automatic context and skips oversized lines", function()
		open("/settings"); send(); assert.is_nil((submitted[3] or {}).context)
		input.close(false); open("printf ready", "shell"); send()
		assert.equals("shell", submitted[3].mode); assert.is_nil(submitted[3].context)
		input.close(false); vim.api.nvim_set_current_buf(source)
		vim.api.nvim_buf_set_lines(source, 0, -1, false, { string.rep("x", 9000) })
		context.observe(); open("bounded")
		assert.is_nil(input.get_editor_context())
	end)
	it("marks only the snapshot present in an existing send draft", function()
		open("retry")
		local previous = assert(input.get_editor_context())
		input.close(false)
		vim.api.nvim_set_current_buf(source)
		vim.api.nvim_buf_set_lines(source, 0, -1, false, { "local newer = 43" })
		context.observe()
		input.set_pending_draft("retry", {}, { options = { context = { previous } } })
		input.show({ close_on_send = false, on_send = function(value, parts, opts) submitted = { value, parts, opts } end })
		local next_snapshot = assert(input.get_editor_context())
		assert.is_not.equals(previous._editor_context.identity, next_snapshot._editor_context.identity)
		send()
		assert.same({ previous }, submitted[3].context)
		input.close(false); open("next")
		assert.equals(next_snapshot._editor_context.identity, input.get_editor_context()._editor_context.identity)
	end)
end)
